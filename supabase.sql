-- ورشة السيارات: مخطط قاعدة البيانات وسياسات الوصول.
-- شغّل هذا الملف مرة واحدة من Supabase Dashboard > SQL Editor.
-- يعيد تشغيله إنشاء/تحديث سياسات الجداول الخمسة التي يديرها هذا التطبيق.
begin;

create table if not exists public.services (
  id integer generated by default as identity primary key,
  slug text not null unique,
  name_ar text not null check (char_length(btrim(name_ar)) between 2 and 120),
  description_ar text not null default '',
  duration_minutes integer not null default 60 check (duration_minutes between 15 and 480),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.customers (
  id uuid primary key default gen_random_uuid(),
  full_name text not null check (char_length(btrim(full_name)) between 2 and 120),
  phone text not null unique check (phone ~ '^[+]9665[0-9]{8}$'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.cars (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references public.customers(id) on delete restrict,
  make text not null check (char_length(btrim(make)) between 1 and 100),
  model text not null check (char_length(btrim(model)) between 1 and 100),
  plate_number text,
  created_at timestamptz not null default now(),
  constraint cars_customer_plate_unique unique (customer_id, plate_number),
  constraint cars_plate_length check (plate_number is null or char_length(plate_number) <= 32)
);

create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  reference_code text not null unique check (reference_code ~ '^WR-[0-9A-F]{12}$'),
  customer_id uuid not null references public.customers(id) on delete restrict,
  car_id uuid not null references public.cars(id) on delete restrict,
  service_id integer not null references public.services(id) on delete restrict,
  appointment_at timestamptz not null,
  duration_minutes integer not null check (duration_minutes between 15 and 480),
  status text not null default 'new' check (status in ('new','confirmed','completed','cancelled')),
  notes text not null default '' check (char_length(notes) <= 2000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'customer' check (role in ('customer','admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists bookings_active_appointment_idx
  on public.bookings (appointment_at)
  where status in ('new','confirmed');
create index if not exists bookings_customer_recent_idx
  on public.bookings (customer_id, created_at desc);
create index if not exists bookings_car_idx on public.bookings (car_id);
create index if not exists bookings_service_status_idx
  on public.bookings (service_id, status);
create index if not exists services_active_name_idx
  on public.services (active, name_ar);

